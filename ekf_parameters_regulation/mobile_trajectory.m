clear all
close all

randn('seed',50); % initialisation du générateur pseudo-aléatoire de matlab à la valeur 50,
                  % cette initialisation sert à ........................

ts=1; % ...............................
A=[1 0 ts 0;0 1 0 ts;0 0 1 0;0 0 0 1];% ...............................
B=[ts^2/2 0;0 ts^2/2;ts 0;0 ts];% ...............................
sigma = 2;% % ...............................
N=500;% % ...............................

x=1000*ones(2,1);%vecteur initialisation de la position de la cible correspond à  x(0|0)
V=zeros(2,1);    %vecteur .....................correspond à ..... 
z=[x;V];         % vecteur  ............
trajectoire=[];  % vecteur pour stocker ...........................

for n = 1:N,
   u= sigma*randn(2,1);% génération du ........., sigma est ......
   z= A*z+B*u;         % équation de ....... pour ..........
   x1=z(1);
   x2=z(2);
   hold on
   plot(x1,x2,'*-r')    % visualisation de .......
   pause(0.001)         % attendre ..... sec avant de ...........
   trajectoire=[trajectoire [x1;x2]];  % trajectoire contient .......
 end


save Traj trajectoire;  % enregistrer la variable trajectoire dans Traj.mat
